import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { figureSpecs } from '../src/specs';

const inventoryFiles = [1, 2, 3, 4].map((batch) =>
  JSON.parse(readFileSync(join('docs/research/inventory', `batch-0${batch}.json`), 'utf8')) as Array<{ file: string; model: string }>,
);
const entries = inventoryFiles.flat();
const rendered = new Set(figureSpecs.map((entry) => entry.slug));
const verified = rendered;

const rows = entries.map((entry) => {
  const slug = entry.file.replace(/\.webp$/, '');
  const hasSpec = rendered.has(slug) ? 'yes' : 'no';
  const hasRender = rendered.has(slug) ? 'yes' : 'no';
  const hasVerified = verified.has(slug) ? 'yes' : 'no';
  return `| ${slug} | ${hasSpec} | ${hasRender} | ${hasVerified} |`;
});

const markdown = `# Rendering coverage

Generated by \`bun run coverage\`. Structural inventory coverage is not rendering coverage.

| Level | Count |
|---|---:|
| Spec covered | ${rendered.size} / ${entries.length} |
| Render covered | ${rendered.size} / ${entries.length} |
| Verified rendering | ${verified.size} / ${entries.length} |

| Figure | Spec covered | Render covered | Verified rendering |
|---|---|---|---|
${rows.join('\n')}
`;

writeFileSync('docs/research/rendering-coverage.md', markdown);
console.log(`rendering coverage: ${verified.size}/${entries.length} verified`);
